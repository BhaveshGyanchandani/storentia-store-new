export function getReviewsForProduct(productId: string): Review[] {
  const seedNum = parseInt(productId.replace("p", ""), 10);
  const count = 3 + (seedNum % 3);
  return Array.from({ length: count }).map((_, i) => ({
    id: `${productId}-r${i}`,
    productId,
    author: REVIEW_AUTHORS[(seedNum + i) % REVIEW_AUTHORS.length],
    rating: 3 + ((seedNum + i) % 3),
    title: REVIEW_TITLES[(seedNum + i * 2) % REVIEW_TITLES.length],
    body: "Well made and the fit is close to true-to-size. Packaging felt considered and shipping was quick. Would recommend to anyone on the fence.",
    date: new Date(2026, (seedNum + i) % 12, 3 + i).toLocaleDateString("en-IN", {
      month: "short",
      day: "numeric",
      year: "numeric",
    }),
    verified: (seedNum + i) % 3 !== 0,
  }));
}

